import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { verifiedProvenance } from "./verify-publication-ui-only.mjs";
const hash = (b) => createHash("sha256").update(b).digest("hex");
const proof = JSON.parse(readFileSync(new URL("./regression-input-only-proof-r1.json",import.meta.url)));
const bytes = readFileSync(proof.reader_check);
assert.equal(hash(bytes), proof.reader_check_sha256);
const check = JSON.parse(bytes);
assert.equal(check.exit_code,0);
assert.equal(check.inputs_changed,false);
assert.equal(check.source_sha256,proof.source_sha256);
const reportBytes = readFileSync(proof.reader_report);
assert.equal(hash(reportBytes),proof.reader_report_sha256);
const report = JSON.parse(reportBytes);
assert.equal(report.status,"pass");
assert.equal(report.productionReaderSyntheticMatrixPassed,true);
assert.equal(report.sourceAndExecutableStable,true);
assert.deepEqual(report.sourceHashes,report.sourceHashesAfter);
assert.deepEqual(report.executableBefore,report.executableAfter);
assert.equal(report.executableBefore.path,"/Library/Developer/CommandLineTools/usr/bin/git");
assert.equal(hash(readFileSync(report.executableBefore.path)),report.executableBefore.sha256);
assert.equal(report.results.length,51);
assert.ok(report.results.every((x)=>x.status==="pass"));
for(const [path, digest] of Object.entries(report.sourceHashes)) assert.equal(hash(readFileSync(new URL("../../../apps/desktop-app/scripts/"+path,import.meta.url))),digest);
assert.equal(verifiedProvenance.buildStampSha256,proof.build_stamp_sha256);
console.log(JSON.stringify({result:"pass",evidence:"verified_prior_actual_reader_regression",newlyExecutedReader:false,cases:51,report:proof.reader_report,onlyAdditionalChange:"index probe contained output namespace"}));
